import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { PGlite } = require('@electric-sql/pglite');
const migration = await readFile(new URL('../supabase/migrations/20261021010000_notifications_replies.sql', import.meta.url),'utf8');
const u = n => `10000000-0000-4000-8000-${String(n).padStart(12,'0')}`;

test('알림함·공개/비공개 코멘트 답글·권한 회수·소유자 삭제를 DB에서 검증한다', async () => {
 const db = new PGlite();
 try {
  await db.exec(`
   create role anon; create role authenticated; create role service_role;
   create schema private;
   create table public.profiles(id uuid primary key,auth_user_id uuid,name text,active boolean);
   create table public.push_subscriptions(profile_id uuid,endpoint text,p256dh text,auth text,lang text);
   create table public.senior_comments(id uuid primary key,report_id uuid,target text,author_id uuid,deleted_at timestamptz);
   create table public.pastoral_note_comments(id uuid primary key,note_id uuid,author_id uuid,deleted_at timestamptz);
   create table public.msg_participants(thread_id uuid,profile_id uuid);
   create table public.msg_posts(id uuid,thread_id uuid,author_id uuid,body text,created_at timestamptz);
   create table public.announcements(id uuid,title text,body text,author_id uuid,created_at timestamptz,deleted_at timestamptz);
   create table public.weekly_reports(id uuid,cell_id uuid,week_start date,created_by uuid,submitted_by uuid,reviewer_user_id uuid,status text,submission_no integer,review_mode text,submitted_at timestamptz);
   create table public.cell_leaders(cell_id uuid,user_id uuid,start_date date,end_date date);
   create table public.leadership_assignments(cell_id uuid,leadership_user_id uuid,start_date date,end_date date);
   create table public.user_roles(user_id uuid,role text);
   create table public.pastoral_notes(id uuid,author_id uuid,visibility text,person_name text,content text,prayer text,created_at timestamptz,active boolean default true);
   create table public.pastoral_note_viewers(note_id uuid,profile_id uuid);
   alter table public.senior_comments add column content text default 'Comment';
   alter table public.pastoral_note_comments add column content text default 'Comment';
   alter table public.senior_comments add column created_at timestamptz default now();
   alter table public.pastoral_note_comments add column created_at timestamptz default now();
   create function private.current_profile_id() returns uuid language sql as $$select nullif(current_setting('test.actor',true),'')::uuid$$;
   create function private.is_admin() returns boolean language sql as $$select false$$;
   create function private.is_senior() returns boolean language sql as $$select private.current_profile_id()='${u(3)}'::uuid$$;
   create function private.has_role(text) returns boolean language sql as $$select false$$;
   create function private.is_cell_leadership(uuid) returns boolean language sql as $$select false$$;
   create function private.can_read_report(uuid) returns boolean language sql as $$select private.current_profile_id() in ('${u(1)}'::uuid,'${u(2)}'::uuid,'${u(3)}'::uuid) and coalesce(current_setting('test.revoked',true),'')<>'yes'$$;
   create function private.can_see_senior_comment(uuid,text) returns boolean language sql as $$select private.can_read_report($1) and ($2='report' or private.current_profile_id() in ('${u(1)}'::uuid,'${u(3)}'::uuid))$$;
   create function private.can_read_pastoral_note(uuid) returns boolean language sql as $$select private.current_profile_id() in ('${u(1)}'::uuid,'${u(3)}'::uuid)$$;
   create function public.notice_list(integer) returns table(id uuid) language sql as $$select null::uuid where false$$;
   insert into public.profiles values ${[1,2,3,4].map(n=>`('${u(n)}','${u(n+10)}','Demo ${n}',true)`).join(',')};
   insert into public.senior_comments(id,report_id,target,author_id) values('${u(21)}','${u(31)}','report','${u(3)}'),('${u(22)}','${u(31)}','pastor_msg','${u(3)}');
   insert into public.pastoral_note_comments(id,note_id,author_id) values('${u(23)}','${u(33)}','${u(3)}');
   insert into public.push_subscriptions values('${u(3)}','endpoint','key','auth','ko');
  `);
  const originalTables=(await db.query("select tablename from pg_tables where schemaname='public' order by tablename")).rows.map(r=>r.tablename);
  const originals=await Promise.all(originalTables.map(async name=>(await db.query(`select coalesce(jsonb_agg(to_jsonb(t) order by to_jsonb(t)::text),'[]') as rows from public.${name} t`)).rows[0].rows));
  await db.exec(migration);
  for(let i=0;i<originalTables.length;i++) {
    const after=(await db.query(`select coalesce(jsonb_agg(to_jsonb(t) order by to_jsonb(t)::text),'[]') as rows from public.${originalTables[i]} t`)).rows[0].rows;
    assert.deepEqual(after,originals[i],originalTables[i]+' original rows preserved');
  }
  const actor = async n => db.exec(`set test.actor='${u(n)}'`);
  const add = (kind,parent,text='Reply') => db.query('select report.cellcare_reply_add($1,$2,$3) as id',[kind,parent,text]);
  const list = (kind,parent) => db.query('select * from report.cellcare_reply_list($1,$2)',[kind,[parent]]);
  await actor(2);
  const reply=(await add('report',u(21))).rows[0].id;
  await assert.rejects(add('report',u(22)), /권한/);
  await assert.rejects(add('note',u(23)), /권한/);
  await assert.rejects(add('report',u(21),'   '));
  await actor(1); await add('report',u(22),'Private reply'); await add('note',u(23));
  await actor(2); assert.equal((await list('report',u(22))).rows.length,0);
  await assert.rejects(db.query('select report.cellcare_reply_delete($1)',[(await list('report',u(21))).rows.find(r=>!r.mine)?.id || u(99)]), /권한/);
  await actor(4); assert.equal((await list('report',u(21))).rows.length,0);
  await assert.rejects(add('report',u(21)), /권한/);
  await actor(3); assert.equal((await db.query('select * from report.cellcare_notification_list()')).rows.length,3);
  await db.exec("set test.revoked='yes'");
  assert.equal((await db.query('select * from report.cellcare_notification_list()')).rows.length,1);
  await db.exec("set test.revoked=''");
  await actor(2); await db.query('select report.cellcare_reply_delete($1)',[reply]);
  assert.equal((await list('report',u(21))).rows.length,0);
  await actor(3);
  assert.equal((await db.query('select * from report.cellcare_notification_list()')).rows.some(n=>n.title==='코멘트에 답글이 달렸습니다' && n.url.endsWith('&comment='+u(21))),false);
  await actor(2);
  await db.exec('set role authenticated');
  await assert.rejects(db.query('select * from report.cellcare_notification_items'),/permission denied/);
  await assert.rejects(db.query("select report.cellcare_notification_record('[]')"),/permission denied/);
  await assert.rejects(db.query('truncate report.cellcare_comment_replies'),/permission denied/);
  await db.exec('reset role');
  await db.exec('set role anon');
  await assert.rejects(db.query('select * from report.cellcare_notification_list()'),/permission denied/);
  await db.exec('reset role');
  const before=(await db.query('select count(*)::int as n from report.cellcare_notification_items')).rows[0].n;
  await db.query('select report.cellcare_notification_record($1)',[JSON.stringify([{endpoint:'endpoint',payload:{tag:'event',title:'Notice',body:'Text',url:'./#report='+u(31)}},{endpoint:'endpoint',payload:{tag:'event',title:'Notice',body:'Text',url:'./#report='+u(31)}}])]);
  assert.equal((await db.query('select count(*)::int as n from report.cellcare_notification_items')).rows[0].n,before+1);
  await db.exec(`insert into public.msg_participants values('${u(61)}','${u(1)}'); insert into public.msg_posts values('${u(62)}','${u(61)}','${u(2)}','Direct message',now())`);
  await actor(1);
  assert.equal((await db.query('select * from report.cellcare_notification_list()')).rows.some(r=>r.body==='Direct message'),true);
  await db.exec(`delete from public.msg_participants where profile_id='${u(1)}'`);
  assert.equal((await db.query('select * from report.cellcare_notification_list()')).rows.some(r=>r.body==='Direct message'),false);
 } finally { await db.close(); }
});
